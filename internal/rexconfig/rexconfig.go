// Package rexconfig connects plugins to Rex's config file.
//
// Rex's require only loads files beside init.lua, so rexd keeps these there:
//
//	init.lua                  the user's file, with one line: require("rexd")
//	rexd.lua                  generated, loads every plugin
//	rexd/plugins/acme/foo.lua the config code of plugin acme.foo
package rexconfig

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/tornikegomareli/rexd/internal/fsutil"
	"github.com/tornikegomareli/rexd/internal/rex"
)

const (
	// generatedHeader starts every file rexd writes beside init.lua.
	generatedHeader = "-- Generated by rexd."

	requireLine = `require("rexd") -- Plugins from rexd. Keep this first, so your own key bindings win.` + "\n"
)

// A require of exactly "rexd" at the start of a line. Requires of other modules
// and lines that start with a comment do not match.
var requireCall = regexp.MustCompile(`^[ \t]*require[ \t]*\(?[ \t]*["']rexd["'][ \t]*\)?`)

// Layout locates rexd's files beside one init.lua.
type Layout struct {
	// Init is the path of Rex's init.lua.
	Init string
}

// Dir is the folder that holds init.lua.
func (l Layout) Dir() string { return filepath.Dir(l.Init) }

// Index is the generated file that loads every plugin.
func (l Layout) Index() string { return filepath.Join(l.Dir(), "rexd.lua") }

// ModuleRoot is the folder that holds the plugins' config code.
func (l Layout) ModuleRoot() string { return filepath.Join(l.Dir(), "rexd") }

// Module is the file that holds the config code of the plugin with this id. The
// dots in an id become folders, the same way Lua's require reads a module name.
func (l Layout) Module(id string) string {
	return filepath.Join(l.ModuleRoot(), "plugins", filepath.FromSlash(strings.ReplaceAll(id, ".", "/"))+".lua")
}

// Entry is one plugin's information for the generated Lua.
type Entry struct {
	ID      string
	Version string
	Dir     string
}

// luaPath renders the Lua expression that adds the plugin's Lua folder to
// package.path, so the plugin can require its other files. Its Lua folder is rex/lua
// if it has one. Otherwise it is lua, unless that holds code for another program, in
// which case the plugin has a rex/lua. The result is empty with neither.
func (e Entry) luaPath() string {
	for _, sub := range []string{"rex/lua", "lua"} {
		root := filepath.Join(e.Dir, filepath.FromSlash(sub))
		if info, err := os.Stat(root); err == nil && info.IsDir() {
			return luaString(root+"/?.lua;"+root+"/?/init.lua;") + " .. package.path"
		}
	}
	return ""
}

// Index renders rexd.lua. It wraps each plugin in pcall, so a plugin that breaks
// later cannot take the user's own bindings down with it. Rex keeps a file's
// earlier result if the whole file fails to load, which would also freeze every
// other plugin. Check validates each plugin without pcall before it gets here.
func Index(entries []Entry) []byte {
	var b bytes.Buffer
	b.WriteString(generatedHeader + " Do not edit: use `rexd install` and `rexd remove`.\n")
	b.WriteString(`rexd = { plugins = {} }

local function load_plugin(id, version, dir)
  local plugin = { id = id, version = version, dir = dir }
  rexd.plugins[id] = plugin
  rexd.plugin = plugin
  local ok, err = pcall(require, "rexd.plugins." .. id)
  rexd.plugin = nil
  if not ok then
    rex.log("error", "rexd: plugin " .. id .. " failed to load: " .. tostring(err))
  end
end

`)
	for _, e := range entries {
		if path := e.luaPath(); path != "" {
			fmt.Fprintf(&b, "package.path = %s\n", path)
		}
		fmt.Fprintf(&b, "load_plugin(%s, %s, %s)\n", luaString(e.ID), luaString(e.Version), luaString(e.Dir))
	}
	return b.Bytes()
}

// WriteIndex writes rexd.lua. It refuses to replace a file rexd did not write.
func (l Layout) WriteIndex(entries []Entry) error {
	if err := l.checkIndexIsOurs(); err != nil {
		return err
	}
	return fsutil.WriteFileAtomic(l.Index(), Index(entries), 0o644)
}

func (l Layout) checkIndexIsOurs() error {
	data, err := os.ReadFile(l.Index())
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if !bytes.HasPrefix(data, []byte(generatedHeader)) {
		return fmt.Errorf("%s exists and rexd did not write it; move it away, because rexd needs that name", l.Index())
	}
	return nil
}

// InstallModule places a plugin's config code beside init.lua. A link stays in
// step with the source, which suits plugin development. What was there stays until
// the new file is complete, so a failure leaves it as it was.
func (l Layout) InstallModule(id, source string, link bool) error {
	target := l.Module(id)
	if link {
		return fsutil.SymlinkAtomic(source, target)
	}
	return fsutil.CopyFileAtomic(source, target)
}

// RemoveModule deletes a plugin's config code and the folders that leaves empty.
func (l Layout) RemoveModule(id string) error {
	target := l.Module(id)
	if err := os.Remove(target); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	root := filepath.Join(l.ModuleRoot(), "plugins")
	for dir := filepath.Dir(target); dir != root && strings.HasPrefix(dir, root); dir = filepath.Dir(dir) {
		if os.Remove(dir) != nil {
			break // Not empty.
		}
	}
	return nil
}

// RemoveAll deletes rexd.lua and every plugin's config code. The rexd folder goes
// only if that leaves it empty, because the user may keep files of their own there.
func (l Layout) RemoveAll() error {
	if err := l.checkIndexIsOurs(); err != nil {
		return err
	}
	if err := os.Remove(l.Index()); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	if err := os.RemoveAll(filepath.Join(l.ModuleRoot(), "plugins")); err != nil {
		return err
	}
	_ = os.Remove(l.ModuleRoot()) // Fails when not empty, which is fine.
	return nil
}

// Check loads one plugin's config code in Rex's checker, without the pcall that
// protects it in rexd.lua, so its errors are reported instead of logged. A
// failure is a *rex.ConfigError. It works without a running server.
func (l Layout) Check(ctx context.Context, client rex.Client, e Entry) error {
	probe, err := os.CreateTemp(l.Dir(), ".rexd-check-*.lua")
	if err != nil {
		return err
	}
	defer os.Remove(probe.Name())
	path := "package.path"
	if found := e.luaPath(); found != "" {
		path = found
	}
	_, err = fmt.Fprintf(probe, `%s It checks one plugin and is deleted right away.
rexd = { plugins = {} }
package.path = %s
rexd.plugin = { id = %s, version = %s, dir = %s }
rexd.plugins[rexd.plugin.id] = rexd.plugin
require(%s)
`, generatedHeader, path, luaString(e.ID), luaString(e.Version), luaString(e.Dir), luaString("rexd.plugins."+e.ID))
	if closeErr := probe.Close(); err == nil {
		err = closeErr
	}
	if err != nil {
		return err
	}
	return client.CheckConfig(ctx, probe.Name())
}

// HasRequire reports whether init.lua loads rexd.
func (l Layout) HasRequire() (bool, error) {
	data, err := os.ReadFile(l.Init)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return hasRequire(data), nil
}

func hasRequire(data []byte) bool {
	comments := blockComments(data)
	offset := 0
	for line := range bytes.Lines(data) {
		if !inComment(comments, offset) && requireCall.Match(line) {
			return true
		}
		offset += len(line)
	}
	return false
}

// withoutRequire removes the require of rexd and keeps everything else. If other
// code shares the line, that code stays. A line that uses the module's value, such
// as require("rexd").x, stays whole, because there is no safe way to change it.
func withoutRequire(data []byte) []byte {
	comments := blockComments(data)
	var out []byte
	offset := 0
	for line := range bytes.Lines(data) {
		start := offset
		offset += len(line)
		call := requireCall.Find(line)
		if call == nil || inComment(comments, start) {
			out = append(out, line...)
			continue
		}
		rest := bytes.TrimLeft(line[len(call):], " \t")
		if len(rest) > 0 && bytes.ContainsRune([]byte(".:([{"), rune(rest[0])) {
			out = append(out, line...)
			continue
		}
		rest = bytes.TrimLeft(bytes.TrimPrefix(rest, []byte(";")), " \t")
		if len(bytes.TrimSpace(rest)) == 0 || bytes.HasPrefix(rest, []byte("--")) {
			continue // Nothing else is on the line. A comment goes with it.
		}
		indent := len(line) - len(bytes.TrimLeft(line, " \t"))
		out = append(append(out, line[:indent]...), rest...)
	}
	return out
}

// blockComments returns where Lua block comments are, as start and end offsets.
// It does not know about strings, so a string holding "--[[" reads as a comment.
// The worst result is that setup adds a second require, which does no harm.
func blockComments(data []byte) [][2]int {
	var comments [][2]int
	for offset := 0; ; {
		found := bytes.Index(data[offset:], []byte("--["))
		if found < 0 {
			return comments
		}
		start := offset + found
		open := start + len("--[")
		level := 0
		for open+level < len(data) && data[open+level] == '=' {
			level++
		}
		if open+level >= len(data) || data[open+level] != '[' {
			offset = open // A line comment that starts with [.
			continue
		}
		body := open + level + 1
		closing := []byte("]" + strings.Repeat("=", level) + "]")
		length := bytes.Index(data[body:], closing)
		if length < 0 {
			return append(comments, [2]int{start, len(data)})
		}
		offset = body + length + len(closing)
		comments = append(comments, [2]int{start, offset})
	}
}

func inComment(comments [][2]int, offset int) bool {
	for _, c := range comments {
		if offset >= c[0] && offset < c[1] {
			return true
		}
	}
	return false
}

// AddRequire makes init.lua load rexd, creating the file if needed. The line goes
// first because the newest binding for a key wins, so the user's bindings further
// down override a plugin's. It returns a function that restores the file.
func (l Layout) AddRequire() (restore func() error, err error) {
	original, err := os.ReadFile(l.Init)
	existed := err == nil
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return nil, err
	}
	restore = func() error { return l.restoreInit(original, existed) }
	if hasRequire(original) {
		return restore, nil
	}
	if err := l.writeInit(append([]byte(requireLine), original...)); err != nil {
		return nil, err
	}
	return restore, nil
}

// RemoveRequire removes the line AddRequire added, keeping everything else. It
// deletes the file only if rexd's line was all it held.
func (l Layout) RemoveRequire() error {
	data, err := os.ReadFile(l.Init)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if !hasRequire(data) {
		return nil
	}
	rest := withoutRequire(data)
	if info, err := os.Lstat(l.Init); len(bytes.TrimSpace(rest)) == 0 && err == nil && info.Mode()&os.ModeSymlink == 0 {
		return os.Remove(l.Init)
	}
	return l.writeInit(rest)
}

func (l Layout) restoreInit(original []byte, existed bool) error {
	if !existed {
		if err := os.Remove(l.Init); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		return nil
	}
	return l.writeInit(original)
}

// writeInit replaces init.lua's content. The write goes through a symbolic link:
// people keep the file in a dotfiles repository, and renaming over the link would
// silently detach Rex's config from it.
func (l Layout) writeInit(data []byte) error {
	target := l.Init
	if resolved, err := filepath.EvalSymlinks(l.Init); err == nil {
		target = resolved
	}
	perm := fs.FileMode(0o644)
	info, err := os.Stat(target)
	switch {
	case err == nil:
		perm = info.Mode().Perm()
	case !errors.Is(err, fs.ErrNotExist):
		return err
	}
	return fsutil.WriteFileAtomic(target, data, perm)
}

// luaString renders s as a Lua 5.1 string literal.
func luaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		switch c := s[i]; {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '\n':
			b.WriteString(`\n`)
		case c < 0x20 || c == 0x7f:
			fmt.Fprintf(&b, `\%03d`, c)
		default:
			b.WriteByte(c) // UTF-8 passes through as bytes.
		}
	}
	b.WriteByte('"')
	return b.String()
}
