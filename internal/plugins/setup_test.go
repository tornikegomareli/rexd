func TestSetupSavesTheServer(t *testing.T) {
	e := newBareEnv(t)
	if _, err := e.m.Setup(context.Background(), SetupOptions{RexConfig: e.init, Server: "unix:///s.sock"}); err != nil {
		t.Fatal(err)
	}
	if e.state().Settings.Server != "unix:///s.sock" {
		t.Errorf("settings = %+v", e.state().Settings)
	}
	calls := e.fake.Calls()
	last := calls[len(calls)-1]
	if !strings.Contains(strings.Join(last, " "), "-S unix:///s.sock") {
		t.Errorf("rex was called without -S: %v", last)
	}
	// Later commands use the saved server without being told again.
	src := configPlugin(t, "acme.foo", "1.0", "-- x")
	if _, err := e.m.Install(context.Background(), Source{Kind: state.KindCopy, Location: src}); err != nil {
		t.Fatal(err)
	}
	calls = e.fake.Calls()
	last = calls[len(calls)-1]
	if !strings.Contains(strings.Join(last, " "), "-S unix:///s.sock") {
		t.Errorf("install did not use the saved server: %v", last)
	}
}

