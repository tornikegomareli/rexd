func TestSetupCreatesConfig(t *testing.T) {
	e := newBareEnv(t)
	settings, err := e.m.Setup(context.Background(), SetupOptions{RexConfig: e.init})
	if err != nil {
		t.Fatal(err)
	}
	if settings.RexConfig != e.init {
		t.Errorf("settings = %+v", settings)
	}
	if !strings.Contains(read(t, e.init), `require("rexd")`) {
		t.Errorf("init.lua = %q", read(t, e.init))
	}
	if !strings.HasPrefix(read(t, e.layout.Index()), "-- Generated by rexd.") {
		t.Errorf("index = %q", read(t, e.layout.Index()))
	}
	if e.state().Settings.RexConfig != e.init {
		t.Errorf("state = %+v", e.state().Settings)
	}
	if e.fake.Reloads() != 1 {
		t.Errorf("reloads = %d", e.fake.Reloads())
	}
}

