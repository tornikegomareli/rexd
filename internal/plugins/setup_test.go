func TestParseSource(t *testing.T) {
	dir := t.TempDir()
	tests := []struct {
		arg, ref string
		link     bool
		want     Source
		wantErr  string
	}{
		{arg: "acme/plugin", want: Source{Kind: state.KindGit, Location: "https://github.com/acme/plugin.git"}},
		{arg: "acme/plugin@v1.2", want: Source{Kind: state.KindGit, Location: "https://github.com/acme/plugin.git", Ref: "v1.2"}},
		{arg: "acme/plugin", ref: "main", want: Source{Kind: state.KindGit, Location: "https://github.com/acme/plugin.git", Ref: "main"}},
		{arg: "https://gitlab.com/a/b.git", ref: "dev", want: Source{Kind: state.KindGit, Location: "https://gitlab.com/a/b.git", Ref: "dev"}},
		{arg: "git@github.com:a/b.git", want: Source{Kind: state.KindGit, Location: "git@github.com:a/b.git"}},
		{arg: "ssh://git@host/a/b.git", want: Source{Kind: state.KindGit, Location: "ssh://git@host/a/b.git"}},
		{arg: dir, want: Source{Kind: state.KindCopy, Location: dir}},
		{arg: dir, link: true, want: Source{Kind: state.KindLink, Location: dir}},
		{arg: "acme/plugin@v1", ref: "main", wantErr: "give the ref once"},
		{arg: "acme/plugin@", wantErr: "no ref after"},
		{arg: "plugin", wantErr: "is not owner/repo"},
		{arg: "a/b/c", wantErr: "is not owner/repo"},
		{arg: "acme/plugin", link: true, wantErr: "--link needs a local folder"},
		{arg: dir, ref: "main", wantErr: "--ref only works"},
		{arg: filepath.Join(dir, "nope"), wantErr: "does not exist"},
	}
	for _, tt := range tests {
		got, err := ParseSource(tt.arg, tt.ref, tt.link)
		if tt.wantErr != "" {
			if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
				t.Errorf("ParseSource(%q): err = %v, want %q", tt.arg, err, tt.wantErr)
			}
			continue
		}
		if err != nil {
			t.Errorf("ParseSource(%q): %v", tt.arg, err)
			continue
		}
		if got != tt.want {
			t.Errorf("ParseSource(%q) = %+v, want %+v", tt.arg, got, tt.want)
		}
	}
}

func TestParseSourceRelativeAndHome(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	if err := os.Mkdir("sub", 0o755); err != nil {
		t.Fatal(err)
	}
	wd, _ := os.Getwd()
	got, err := ParseSource("./sub", "", false)
	if err != nil || got.Location != filepath.Join(wd, "sub") {
		t.Fatalf("./sub: %+v, %v", got, err)
	}
	file := filepath.Join(dir, "file.txt")
	os.WriteFile(file, nil, 0o644)
	if _, err := ParseSource(file, "", false); err == nil || !strings.Contains(err.Error(), "not a folder") {
		t.Fatalf("file: %v", err)
	}

	t.Setenv("HOME", dir)
	got, err = ParseSource("~/sub", "", false)
	if err != nil || got.Location != filepath.Join(dir, "sub") {
		t.Fatalf("~/sub: %+v, %v", got, err)
	}
}
