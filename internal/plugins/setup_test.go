func TestTeardownKeepsPlugins(t *testing.T) {
	e := newEnv(t)
	write(t, e.init, read(t, e.init)+"-- mine\n")
	src := configPlugin(t, "acme.foo", "1.0", "-- x")
	if _, err := e.m.Install(context.Background(), Source{Kind: state.KindCopy, Location: src}); err != nil {
		t.Fatal(err)
	}

	if err := e.m.Teardown(context.Background(), TeardownOptions{}); err != nil {
		t.Fatal(err)
	}
	if got := read(t, e.init); got != "-- mine\n" {
		t.Errorf("init.lua = %q", got)
	}
	missing(t, e.layout.Index())
	missing(t, e.layout.ModuleRoot())
	if _, err := os.Stat(e.dirs.Plugin("acme.foo")); err != nil {
		t.Errorf("the plugin should stay: %v", err)
	}
	saved := e.state()
	if saved.Settings.RexConfig != "" || saved.Plugins["acme.foo"] == nil {
		t.Errorf("state = %+v", saved)
	}

	// A later setup brings the plugin back.
	if _, err := e.m.Setup(context.Background(), SetupOptions{RexConfig: e.init}); err != nil {
		t.Fatal(err)
	}
	if got := read(t, e.layout.Module("acme.foo")); got != "-- x" {
		t.Errorf("module = %q", got)
	}
	if !strings.Contains(read(t, e.layout.Index()), "acme.foo") {
		t.Error("the plugin is not back in the index")
	}
}

